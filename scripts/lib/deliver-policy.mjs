// Политика ретраев доставки апдейта в eve. Мост однопоточный: пока deliver() ретраит,
// getUpdates стоит и offset не двигается — поэтому вечный ретрай допустим только для
// ошибок, которые лечатся временем (сеть, 5xx, и «повтори позже» 408/425/429). Любой
// другой 4xx — апдейт битый навсегда: eve его не примет ни с какой попытки, и один
// такой апдейт заморозил бы доставку по ВСЕМ чатам.
const RETRYABLE_4XX = new Set([408, 425, 429]);

export function isRetryableDeliverStatus(status) {
  return status >= 500 || RETRYABLE_4XX.has(status);
}
